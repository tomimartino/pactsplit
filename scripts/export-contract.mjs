import { readFile, writeFile, mkdir } from "node:fs/promises";
const artifact = JSON.parse(
  await readFile(
    new URL(
      "../contracts/artifacts/contracts/PactSplit.sol/PactSplit.json",
      import.meta.url,
    ),
    "utf8",
  ),
);
await mkdir(new URL("../src/generated/", import.meta.url), { recursive: true });
await writeFile(
  new URL("../src/generated/pactsplit.ts", import.meta.url),
  `// Generated by npm run contracts:compile. Do not edit by hand.\nexport const pactSplitAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
await mkdir(new URL("../public/", import.meta.url), { recursive: true });
await writeFile(
  new URL("../public/deployment-artifact.json", import.meta.url),
  JSON.stringify({ abi: artifact.abi, bytecode: artifact.bytecode }),
);
console.log("Exported contract ABI and wallet deployment artifact.");
